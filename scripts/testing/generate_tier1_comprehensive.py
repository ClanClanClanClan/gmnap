def generate_name(region: str, patterns: Dict) -> Dict:
    """Generate a synthetic test name for a region."""
    surname = random.choice(patterns["surnames"])

    if patterns["given_names"]:
        given_name = random.choice(patterns["given_names"])
        full_name = f"{given_name} {surname}"
    else:
        full_name = surname  # Historical mononyms

    return {
        "CanonicalNative": full_name,
        "Region": region.lower(),
        "Source": "synthetic",
        "LinguisticPattern": "standard",
    }


def generate_dataset():
    """Generate comprehensive Tier 1 test dataset."""
    dataset = []
    stats = {"total": 0, "by_region": {}}

    print("Generating Tier 1 Comprehensive Regional Dataset...")
    print(f"Target: {sum(p['count'] for p in REGIONAL_PATTERNS.values())} test cases")
    print(f"Regions: {len(REGIONAL_PATTERNS)} (100% coverage)")
    print()

    for region_code, patterns in REGIONAL_PATTERNS.items():
        count = patterns["count"]
        region_full = f"{region_code.lower()}_synthetic"

        for i in range(count):
            entry = generate_name(region_full, patterns)
            dataset.append(entry)

        stats["by_region"][region_code] = count
        stats["total"] += count

        print(f"✓ {region_code}: Generated {count} test cases")

    return dataset, stats


